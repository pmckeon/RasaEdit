"""Writes MissionSceneSchema.h (repository root) from the harness's schema dump: the contract System.Text.Json reads Rasa.NET's scene
documents with (MissionContentCodec.Options; MissionSceneDefinition and MissionExperienceDefinition with every type they reach).
  dotnet <harness folder>/Rasa.Test.dll --schema scene_schema.json
  python tools/missioncheck/make_scene_schema.py scene_schema.json
Rerun both after updating Rasa.NET."""
import json, os, sys

schema = json.load(open(sys.argv[1], encoding='utf-8'))
text = json.dumps(schema, separators=(',', ':'), sort_keys=True)
chunks = [text[i:i + 1800] for i in range(0, len(text), 1800)]
for c in chunks:
    assert ')schema"' not in c
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'MissionSceneSchema.h')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/missioncheck/make_scene_schema.py from the harness\'s --schema dump - do not edit.\n')
    f.write('// The System.Text.Json contract (JsonTypeInfo under MissionContentCodec.Options) of Rasa.NET\'s scene documents:\n')
    f.write('// %d object types reachable from MissionSceneDefinition and MissionExperienceDefinition.\n' % len(schema['types']))
    f.write('#pragma once\n\ninline const char* missionSceneSchemaJson() {\n    return\n')
    for c in chunks:
        f.write('        R"schema(' + c + ')schema"\n')
    f.write('        ;\n}\n')
print(out, len(text), 'bytes')
