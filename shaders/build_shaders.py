#!/usr/bin/env python3
"""Compile the viewport shaders with DXC to DXIL (Direct3D 12) and SPIR-V (Vulkan) and write
ShaderBytecode.h with the results as byte arrays. Only needed after editing a .hlsl file.

Usage: python build_shaders.py [path/to/dxc]
DXC ships with the Windows SDK and the Vulkan SDK, or from github.com/microsoft/DirectXShaderCompiler/releases.
"""
import os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(HERE, '..', 'ShaderBytecode.h')
SHADERS = [   # (array name prefix, source, entry point, profile)
    ('sceneVertex', 'scene.hlsl', 'vsMain', 'vs_6_0'),
    ('sceneFragment', 'scene.hlsl', 'psMain', 'ps_6_0'),
    ('shadowFragment', 'scene.hlsl', 'psShadow', 'ps_6_0'),
    ('terrainVertex', 'terrain.hlsl', 'vsMain', 'vs_6_0'),
    ('terrainFragment', 'terrain.hlsl', 'psMain', 'ps_6_0'),
]

def compile(dxc, source, entry, profile, spirv):
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'out.bin')
        cmd = [dxc, '-T', profile, '-E', entry, '-O3', '-Fo', out, os.path.join(HERE, source)]
        if spirv:
            cmd[1:1] = ['-spirv', '-fspv-target-env=vulkan1.0']
        subprocess.run(cmd, check=True)
        return open(out, 'rb').read()

def array(name, data):
    lines = ['static const unsigned char %s[%d] = {' % (name, len(data))]
    for k in range(0, len(data), 16):
        lines.append('    ' + ', '.join('0x%02x' % b for b in data[k:k + 16]) + ',')
    lines.append('};')
    return '\n'.join(lines)

def main():
    dxc = sys.argv[1] if len(sys.argv) > 1 else 'dxc'
    parts = ['// Generated by shaders/build_shaders.py - do not edit.', '#pragma once', '']
    for name, source, entry, profile in SHADERS:
        parts.append(array(name + 'Dxil', compile(dxc, source, entry, profile, False)))
        parts.append(array(name + 'Spirv', compile(dxc, source, entry, profile, True)))
        parts.append('')
    open(OUTPUT, 'w').write('\n'.join(parts) + '\n')
    print('wrote', os.path.normpath(OUTPUT))

if __name__ == '__main__':
    main()
